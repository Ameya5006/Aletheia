"""Export the real FastAPI schema and public responses; never load source data."""

import json
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

from fastapi.testclient import TestClient

from aletheia.application.api import create_app
from aletheia.application.config import Settings
from aletheia.application.release import VerifiedRelease, build_release

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root))
from tests.application.conftest import ISSUER  # noqa: E402


class UnavailableStore:
    @property
    def engine(self):
        raise ValueError("Public contract export has no database")


class UnavailableVerifier:
    def ready(self):
        return False

    def key(self, kid):
        from aletheia.application.auth import ServiceError

        raise ServiceError(503, "identity_unavailable")


with TemporaryDirectory(dir=root / "artifacts/stage2-verification") as temp:
    release_path = Path(temp) / "release"
    release = VerifiedRelease(release_path, build_release(root, release_path))
    settings = Settings(
        app_env="test",
        database_url="postgresql+psycopg://unused@localhost/test",
        release_root=release.root,
        release_sha256=release.digest,
        model_version="1",
        oidc_issuer=ISSUER,
        oidc_audience="aletheia-api",
        oidc_jwks_uri=ISSUER + "/jwks",
        oidc_max_token_lifetime_seconds=600,
        provider_token_lifetime_seconds=600,
        bootstrap_oidc_issuer=ISSUER,
        bootstrap_oidc_sub="synthetic-admin",
        deployment_pin_path=Path(temp) / "deployment.json",
    )
    app = create_app(settings, release, UnavailableStore(), UnavailableVerifier())
    schema = app.openapi()
    # No real UUIDs or timestamped model releases are generated by these reads.
    routes = [
        "/health/live",
        "/health/ready",
        "/models/current",
        "/models/current/card",
        "/demo/cases",
        "/explanations/global",
        "/explanations/local/synthetic-discharge-v1",
        "/audits/stability",
        "/audits/subgroups",
        "/counterfactuals/feasibility",
    ]
    with TestClient(app) as client:
        samples = {path: client.get("/api/v1" + path).json() for path in routes}
    output = root / "artifacts/stage2-verification"
    output.mkdir(exist_ok=True)
    (output / "openapi.json").write_text(json.dumps(schema, indent=2) + "\n")
    (output / "public-responses.json").write_text(json.dumps(samples, indent=2) + "\n")
    print("Exported real OpenAPI and 10 public FastAPI responses; no source data.")
